using System.Globalization;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using MicroLIMS.Application.Abstractions.Pdf;
using MicroLIMS.Application.Abstractions.Persistence;
using MicroLIMS.Application.Abstractions.Word;
using MicroLIMS.Application.Helpers;
using MicroLIMS.Domain.Enums;

namespace MicroLIMS.Application.Services.Spc;

public enum ControlChartReportFormat { Pdf, Word }

// One chart in the report: the exact query it was charted from, and the
// picture the browser drew of it.
public record ControlChartReportSection(
    string TestCode,
    string SubjectName,
    SampleCategory? Category,
    DateTime? FromDate,
    DateTime? ToDate,
    DateTime? CalculationFrom,
    DateTime? CalculationTo,
    bool ApprovedOnly,
    ControlChartSettings Settings,
    CapabilityBasis CapabilityBasis,
    double? CustomLsl,
    double? CustomUsl,
    string ChartType,
    string? Title,
    string ImagePng);

public record ControlChartReportRequest(
    string Title,
    string? Notes,
    ControlChartReportFormat Format,
    bool IncludeSummary,
    List<ControlChartReportSection> Sections);

public record GeneratedReport(byte[] Content, string FileName, string ContentType);

// Builds one PDF or Word report from many control charts. Only the chart
// pictures come from the browser; every figure printed beside them -
// statistics, proposed and current limits, capability, flagged points -
// is recomputed here from the section's own query at generation time, so
// the tables cannot disagree with the data. Each report is logged as a
// data export.
public class ControlChartReportService
{
    public const int MaxSections = 60;
    public const int MaxImageBytes = 4 * 1024 * 1024;
    public const int MaxImagePixels = 4000;
    private const int MaxFlaggedRows = 100;

    private readonly ControlChartService _charts;
    private readonly IPdfGenerator _pdf;
    private readonly IWordGenerator _word;
    private readonly DataExportAuditService _exportAudit;
    private readonly IMicroLimsDbContext _db;
    private readonly TimeProvider _time;

    public ControlChartReportService(ControlChartService charts, IPdfGenerator pdf, IWordGenerator word,
        DataExportAuditService exportAudit, IMicroLimsDbContext db, TimeProvider? time = null)
    {
        _charts = charts;
        _pdf = pdf;
        _word = word;
        _exportAudit = exportAudit;
        _db = db;
        _time = time ?? TimeProvider.System;
    }

    public async Task<GeneratedReport> GenerateAsync(ControlChartReportRequest r, int userId, IReadOnlyCollection<int>? sectionIds = null, CancellationToken ct = default)
    {
        var title = r.Title?.Trim();
        if (string.IsNullOrWhiteSpace(title)) throw new InvalidOperationException("A report title is required.");
        if (title.Length > 200) throw new InvalidOperationException("The report title must be 200 characters or fewer.");
        if (r.Sections is null || r.Sections.Count == 0) throw new InvalidOperationException("Add at least one chart to the report.");
        if (r.Sections.Count > MaxSections) throw new InvalidOperationException($"A report can hold at most {MaxSections} charts.");

        var images = r.Sections.Select((s, i) => DecodeImage(s.ImagePng, i + 1)).ToList();

        var charts = new List<ControlChartResult>();
        foreach (var s in r.Sections)
        {
            charts.Add(await _charts.GetChartAsync(new ControlChartQuery(
                s.TestCode, s.SubjectName, s.Category, s.FromDate, s.ToDate, s.CalculationFrom, s.CalculationTo, s.ApprovedOnly,
                s.Settings, s.CapabilityBasis, s.CustomLsl, s.CustomUsl), sectionIds, ct));
        }

        var now = _time.GetUtcNow().UtcDateTime;
        var userName = await _db.Users.Where(u => u.Id == userId).Select(u => u.FullName).FirstOrDefaultAsync(ct) ?? "Unknown user";
        var documentId = $"CCR-{now:yyyyMMdd-HHmmss}";

        var doc = new ReportDocument
        {
            Kind = "Control Chart Report",
            DocumentId = documentId,
            Subtitle = title,
            BadgeText = $"{charts.Count} CHART{(charts.Count == 1 ? "" : "S")}",
            HeaderNote = $"Generated by {userName} · {now.ToString("dd-MMM-yyyy HH:mm", CultureInfo.InvariantCulture)} UTC"
        };

        if (!string.IsNullOrWhiteSpace(r.Notes))
        {
            doc.Blocks.Add(new CardBlock
            {
                Title = "Report notes",
                Tone = ReportTone.Neutral,
                MetaLines = r.Notes.Split('\n').Select(l => l.TrimEnd()).Where(l => l.Length > 0).ToList()
            });
        }

        if (r.IncludeSummary) doc.Blocks.Add(Summary(r.Sections, charts));

        // On the first page, where the summary leaves room, rather than on
        // a page of its own at the end.
        doc.Blocks.Add(new CardBlock
        {
            Title = "About this report",
            Tone = ReportTone.Neutral,
            MetaLines = new List<string>
            {
                "Charts were drawn from the MicroLIMS control chart data; every figure in the tables was recomputed by the server from the stated query when this report was generated.",
                "Results below the detection limit are plotted at half the limit. Only the latest retest round of each result is used. Dates are sampling dates.",
                "Cp/Cpk use the within (moving range) sigma and Pp/Ppk the overall standard deviation. With only an upper limit Cpk = Cpu. Indices assume approximately normal data."
            }
        });

        for (var i = 0; i < charts.Count; i++)
            AddSection(doc, i + 1, r.Sections[i], charts[i], images[i]);



        var isPdf = r.Format == ControlChartReportFormat.Pdf;
        var content = isPdf ? await _pdf.GenerateReportAsync(doc) : await _word.GenerateReportAsync(doc);

        var filter = JsonSerializer.Serialize(new
        {
            documentId,
            title,
            format = r.Format.ToString(),
            sections = r.Sections.Select(s => new { s.TestCode, s.SubjectName, category = s.Category?.ToString(), s.FromDate, s.ToDate, s.ChartType })
        });
        await _exportAudit.LogExportAsync(userId, filter, charts.Count, isPdf ? "ControlChartReportPdf" : "ControlChartReportWord");

        var safeTitle = new string(title.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray()).Trim('_');
        if (safeTitle.Length > 60) safeTitle = safeTitle[..60];
        return isPdf
            ? new GeneratedReport(content, $"{documentId}_{safeTitle}.pdf", "application/pdf")
            : new GeneratedReport(content, $"{documentId}_{safeTitle}.docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document");
    }

    private static byte[] DecodeImage(string? base64, int index)
    {
        if (string.IsNullOrWhiteSpace(base64)) throw new InvalidOperationException($"Chart {index} has no image.");
        var comma = base64.IndexOf(',');
        if (base64.StartsWith("data:", StringComparison.Ordinal) && comma > 0) base64 = base64[(comma + 1)..];

        byte[] bytes;
        try { bytes = Convert.FromBase64String(base64); }
        catch (FormatException) { throw new InvalidOperationException($"Chart {index} image is not valid base64."); }

        if (bytes.Length > MaxImageBytes) throw new InvalidOperationException($"Chart {index} image is larger than {MaxImageBytes / (1024 * 1024)} MB.");
        if (!PngHeader.TryReadSize(bytes, out var w, out var h)) throw new InvalidOperationException($"Chart {index} image is not a PNG.");
        if (w > MaxImagePixels || h > MaxImagePixels) throw new InvalidOperationException($"Chart {index} image is larger than {MaxImagePixels} × {MaxImagePixels} pixels.");
        return bytes;
    }

    private static TableBlock Summary(List<ControlChartReportSection> sections, List<ControlChartResult> charts) => new()
    {
        Label = "Summary",
        Summary = "Proposed limits use each chart's own settings; current limits are the configured ones.",
        Table = new ReportTable
        {
            Columns = new List<TableColumn>
            {
                new("#", 0.04), new("Location", 0.16), new("Test", 0.11), new("Chart", 0.12), new("n", 0.05), new("Mean", 0.07),
                new("Sigma", 0.07), new("Proposed alert / action", 0.12), new("Current alert / action", 0.12), new("Cpk", 0.06), new("Flagged", 0.08)
            },
            Rows = charts.Select((c, i) =>
            {
                var s = c.Statistics;
                return new List<string>
                {
                    (i + 1).ToString(CultureInfo.InvariantCulture), c.SubjectName, c.TestDisplayName, sections[i].ChartType,
                    s.Count.ToString(CultureInfo.InvariantCulture), F(s.Mean), F(s.SigmaUsed),
                    $"{F(s.Limits.AlertUpper)} / {F(s.Limits.ActionUpper)}", $"{F(c.CurrentLimits.Alert)} / {F(c.CurrentLimits.Action)}",
                    F(s.Capability.Cpk), s.RuleViolations.Count(v => v.Length > 0).ToString(CultureInfo.InvariantCulture)
                };
            }).ToList()
        }
    };

    private static void AddSection(ReportDocument doc, int number, ControlChartReportSection section, ControlChartResult c, byte[] png)
    {
        var s = c.Statistics;
        var cap = s.Capability;
        var heading = string.IsNullOrWhiteSpace(section.Title) ? $"{c.TestDisplayName} - {c.SubjectName}" : section.Title.Trim();
        var flagged = c.Points.Where(p => p.Rules.Length > 0).ToList();
        var settings = c.Settings;

        // One chart per page; the first follows the header directly when
        // there are no notes or summary before it.
        if (doc.Blocks.Count > 0) doc.Blocks.Add(new PageBreakBlock());
        doc.Blocks.Add(new HeadingBlock { Text = $"{number}. {heading}" });
        doc.Blocks.Add(new StripBlock
        {
            Label = "Basis",
            Items = new List<(string, string, string?)>
            {
                ("Test", c.TestDisplayName, c.TestCode),
                ("Location", c.SubjectName, null),
                ("Period", Period(section.FromDate, section.ToDate), section.ApprovedOnly ? "Approved results only" : "All results")
            }
        });
        doc.Blocks.Add(new StripBlock
        {
            Label = "Limit method",
            Items = new List<(string, string, string?)>
            {
                ("Method", ControlChartService.MethodLabel(settings).Replace("σ", " sigma"),
                    "Estimated from " + (section.CalculationFrom is null && section.CalculationTo is null ? "the whole period" : Period(section.CalculationFrom, section.CalculationTo))),
                ("Rounding", RoundingLabel(settings.Rounding), null),
                ("Tests applied", settings.EnabledRules.Count == 0 ? "None" : string.Join(", ", settings.EnabledRules.OrderBy(x => x)), "Minitab special-cause tests")
            }
        });
        doc.Blocks.Add(new ImageBlock { Png = png, Caption = $"Figure {number}. {section.ChartType} - {c.TestDisplayName}, {c.SubjectName}" });
        doc.Blocks.Add(new StripBlock
        {
            Label = "Statistics",
            Items = new List<(string, string, string?)>
            {
                ("Results (n)", s.Count.ToString(CultureInfo.InvariantCulture), s.BelowMinimumPoints ? $"Below minimum of {settings.MinimumPoints}" : null),
                ("Mean", F(s.Mean), c.Unit),
                ("Median", F(s.Median), null),
                ("Std deviation", F(s.StandardDeviation), "overall"),
                ("Sigma within", F(s.SigmaWithin), "MR-bar / d2"),
                ("Min - Max", $"{F(s.Min)} - {F(s.Max)}", c.ImputedPointCount > 0 ? $"{c.ImputedPointCount} below LOD" : null)
            }
        });
        doc.Blocks.Add(new StripBlock
        {
            Label = "Limits",
            Items = new List<(string, string, string?)>
            {
                ("Proposed alert", F(s.Limits.AlertUpper), null),
                ("Proposed action", F(s.Limits.ActionUpper), null),
                ("Current alert", F(c.CurrentLimits.Alert), null),
                ("Current action", F(c.CurrentLimits.Action), null),
                ("Specification", F(c.CurrentLimits.SpecUpper), null),
                ("Flagged points", flagged.Count.ToString(CultureInfo.InvariantCulture), null)
            }
        });
        doc.Blocks.Add(new StripBlock
        {
            Label = $"Process capability against {Basis(c.CapabilityBasis)}",
            Items = new List<(string, string, string?)>
            {
                ("LSL / USL", $"{F(cap.Lsl)} / {F(cap.Usl)}", null),
                ("Cp", F(cap.Cp), null),
                ("Cpk", F(cap.Cpk), Rating(cap.Cpk)),
                ("Pp", F(cap.Pp), null),
                ("Ppk", F(cap.Ppk), Rating(cap.Ppk)),
                ("Outside limits", cap.ObservedPercentOutside is null ? "—" : $"{F(cap.ObservedPercentOutside)} %",
                    cap.ExpectedPercentOutside is null ? null : $"expected {F(cap.ExpectedPercentOutside, 3)} %")
            }
        });

        if (flagged.Count > 0)
        {
            doc.Blocks.Add(new TableBlock
            {
                Label = "Flagged points",
                Summary = flagged.Count > MaxFlaggedRows ? $"First {MaxFlaggedRows} of {flagged.Count} flagged points." : null,
                BadgeText = $"{flagged.Count} FLAGGED",
                BadgeTone = ReportTone.Warning,
                Table = new ReportTable
                {
                    Columns = new List<TableColumn> { new("Date", 0.14), new("Reference", 0.2), new("Result", 0.12), new("Failed tests", 0.54) },
                    Rows = flagged.Take(MaxFlaggedRows).Select(p => new List<string>
                    {
                        p.Date.ToString("dd-MMM-yyyy", CultureInfo.InvariantCulture), p.ReferenceNumber, p.ReportedValue,
                        string.Join("; ", p.Rules.Select(rule => $"{rule}: {ControlChartCalculator.RuleDescriptions[rule]}"))
                    }).ToList()
                }
            });
        }
    }

    private static string RoundingLabel(LimitRounding r) => r switch
    {
        LimitRounding.OneDecimal => "1 decimal",
        LimitRounding.TwoDecimals => "2 decimals",
        LimitRounding.UpToWholeNumber => "Up to whole number",
        _ => "None"
    };

    private static string Basis(CapabilityBasis b) => b switch
    {
        CapabilityBasis.ActionLimit => "the action limit",
        CapabilityBasis.AlertLimit => "the alert limit",
        CapabilityBasis.Custom => "custom limits",
        _ => "the specification"
    };

    private static string? Rating(double? index) => index switch
    {
        null => null,
        >= 1.33 => "capable",
        >= 1.0 => "marginal",
        _ => "not capable"
    };

    private static string Period(DateTime? from, DateTime? to) =>
        $"{from?.ToString("dd-MMM-yyyy", CultureInfo.InvariantCulture) ?? "start"} - {to?.ToString("dd-MMM-yyyy", CultureInfo.InvariantCulture) ?? "now"}";

    private static string F(double? v, int digits = 2) =>
        v is null || double.IsNaN(v.Value) ? "—" : Math.Round(v.Value, digits).ToString(CultureInfo.InvariantCulture);
}
