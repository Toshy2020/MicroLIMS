using System.IO.Compression;
using DocumentFormat.OpenXml.Packaging;
using DocumentFormat.OpenXml.Validation;
using MicroLIMS.Application.Abstractions.Pdf;
using MicroLIMS.Application.Helpers;
using MicroLIMS.Infrastructure.Pdf;
using MicroLIMS.Infrastructure.Word;
using SkiaSharp;
using UglyToad.PdfPig;
using Xunit;

namespace MicroLIMS.Tests.UnitTests;

// The image block (charts) in both renderers, and the Word renderer's
// output as a whole: valid OOXML, every block type present.
public class ReportImageAndWordRenderingTests
{
    internal static byte[] Png(int width = 400, int height = 200, bool transparent = false)
    {
        using var bmp = new SKBitmap(width, height);
        using (var canvas = new SKCanvas(bmp))
        {
            canvas.Clear(transparent ? SKColors.Transparent : SKColors.White);
            using var paint = new SKPaint { Color = SKColors.Blue, StrokeWidth = 4 };
            canvas.DrawLine(0, height, width, 0, paint);
        }
        using var data = bmp.Encode(SKEncodedImageFormat.Png, 100);
        return data.ToArray();
    }

    private static ReportDocument Document(params ReportBlock[] blocks)
    {
        var doc = new ReportDocument
        {
            Kind = "Control Chart Report", DocumentId = "CCR-TEST", Subtitle = "Annual EM review", BadgeText = "2 CHARTS",
            HeaderNote = "Generated by Test User"
        };
        doc.Blocks.AddRange(blocks);
        return doc;
    }

    [Fact]
    public void PngHeader_ReadsSize_AndRejectsOtherFiles()
    {
        Assert.True(PngHeader.TryReadSize(Png(321, 123), out var w, out var h));
        Assert.Equal((321, 123), (w, h));
        Assert.False(PngHeader.TryReadSize("%PDF-1.4 not an image"u8.ToArray(), out _, out _));
        Assert.False(PngHeader.TryReadSize(Array.Empty<byte>(), out _, out _));
    }

    [Fact]
    public void Pdf_EmbedsEachImage_WithItsCaption()
    {
        var bytes = new ReportPdfRenderer().Render(Document(
            new ImageBlock { Png = Png(), Caption = "Figure 1. I-MR chart" },
            new ImageBlock { Png = Png(300, 300, transparent: true), Caption = "Figure 2. Histogram" }));

        using var pdf = PdfDocument.Open(bytes);
        var images = pdf.GetPages().SelectMany(p => p.GetImages()).ToList();
        Assert.Equal(2, images.Count);
        Assert.Equal(400, images[0].WidthInSamples);
        Assert.Equal(200, images[0].HeightInSamples);
        var text = string.Join(" ", pdf.GetPages().SelectMany(p => p.GetWords()).Select(w => w.Text));
        Assert.Contains("Figure 1.", text);
        Assert.Contains("Histogram", text);
    }

    [Fact]
    public void Pdf_TallImages_StartNewPagesInsteadOfOverflowing()
    {
        var blocks = Enumerable.Range(0, 4).Select(_ => (ReportBlock)new ImageBlock { Png = Png(800, 900) }).ToArray();
        using var pdf = PdfDocument.Open(new ReportPdfRenderer().Render(Document(blocks)));

        Assert.True(pdf.NumberOfPages >= 4);
        foreach (var page in pdf.GetPages())
            foreach (var image in page.GetImages())
                Assert.True(image.Bounds.Bottom >= 0 && image.Bounds.Top <= page.Height);
    }

    [Fact]
    public void Word_IsValidOoxml_WithEveryBlockType()
    {
        var doc = Document(
            new CardBlock { Title = "Report notes", MetaLines = new() { "Reviewed for the annual limit review." }, Details = new() { ("Room", "Filling") } },
            new HeadingBlock { Text = "1. EM TAMC - Filling Room" },
            new StripBlock { Label = "Statistics", Items = new() { ("Mean", "2.4", "CFU/Plate"), ("n", "40", null) } },
            new TwoColumnBlock { LeftLabel = "Identity", Left = new() { ("Test", "EM TAMC") }, RightLabel = "Dates", Right = new() { ("From", "01-Jan-2026") } },
            new ImageBlock { Png = Png(), Caption = "Figure 1. I-MR chart" },
            new TableBlock
            {
                Label = "Flagged points", BadgeText = "1 FLAGGED", BadgeTone = ReportTone.Warning, Legend = "Tests per Minitab",
                Table = new ReportTable
                {
                    Columns = new() { new("Date", 0.3), new("Reference", 0.3), new("Status", 0.4) },
                    Rows = new() { new() { "01-Jan-2026", "EM-001 & <x>", "ActionLimitExceeded" } },
                    StatusColumnIndex = 2
                }
            },
            new ListBlock { Label = "History", Rows = new() { ("Created", "01-Jan-2026\nTest User") } },
            new SignatureBlock { Signatures = new() { new SignatureEntry { PrintedName = "Test User", Username = "test", Role = "Section Head", SignedAt = "now", Meaning = "Approved", Comment = "OK" } } });

        var bytes = new DocxReportRenderer().Render(doc);

        using var stream = new MemoryStream(bytes);
        using var word = WordprocessingDocument.Open(stream, false);
        var errors = new OpenXmlValidator().Validate(word).Select(e => $"{e.Part?.Uri}: {e.Description}").ToList();
        Assert.True(errors.Count == 0, string.Join("\n", errors));

        var text = word.MainDocumentPart!.Document.Body!.InnerText;
        Assert.Contains("CCR-TEST", text);
        Assert.Contains("1. EM TAMC - FILLING ROOM", text);
        Assert.Contains("EM-001 & <x>", text);
        Assert.Contains("Figure 1. I-MR chart", text);
        Assert.Single(word.MainDocumentPart.ImageParts);
        Assert.Contains("controlled document", word.MainDocumentPart.FooterParts.Single().Footer.InnerText);
    }

    [Fact]
    public void Word_ImageIsScaledToTheContentWidth()
    {
        var bytes = new DocxReportRenderer().Render(Document(new ImageBlock { Png = Png(2400, 800) }));

        using var zip = new ZipArchive(new MemoryStream(bytes));
        using var reader = new StreamReader(zip.GetEntry("word/document.xml")!.Open());
        var xml = reader.ReadToEnd();
        // Content width: (11906 - 2 x 907) twips x 635 EMU per twip; height keeps the 3:1 aspect.
        Assert.Contains($"cx=\"{(11906 - 2 * 907) * 635L}\" cy=\"{(11906 - 2 * 907) * 635L / 3}\"", xml);
    }

    [Fact]
    public void Word_InvalidImage_IsRefused()
    {
        Assert.Throws<InvalidOperationException>(() =>
            new DocxReportRenderer().Render(Document(new ImageBlock { Png = new byte[] { 1, 2, 3 } })));
    }
}
