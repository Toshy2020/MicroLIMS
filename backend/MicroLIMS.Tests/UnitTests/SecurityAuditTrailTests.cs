    // ---------- 9. Automatic lockout, actor = system ----------

    [Fact]
    public async Task AutomaticLockout_RecordsAccountLocked_WithSystemActor()
    {
        using var db = CreateDbContext();
        var user = SeedUser(db);
        var (_, auth) = CreateServices(db);

        for (var attempt = 0; attempt < 5; attempt++)
            await auth.LoginAsync("analyst1", "TotallyWrong9!");

        var locked = Assert.Single(await EventsAsync(db, SecurityEventCodes.AccountLocked));
        Assert.True(locked.ActorIsSystem);
        Assert.Null(locked.ActorUserId); // no person locked this account
        Assert.Equal(user.Id, locked.TargetUserId);
        Assert.Contains("Automatic lockout", locked.Reason);
    }

