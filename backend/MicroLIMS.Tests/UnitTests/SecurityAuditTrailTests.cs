    // ---------- 11. No credentials ever reach the trail ----------

    [Fact]
    public async Task SecurityEvents_NeverContainRawTokensOrPasswords()
    {
        using var db = CreateDbContext();
        var user = SeedUser(db);
        var (users, auth) = CreateServices(db);

        // Exercise every flow that handles a credential or a token.
        var login = await auth.LoginAsync("analyst1", CurrentPassword);
        var rotated = await auth.RefreshAsync(login.RefreshToken!);
        await auth.LogoutAsync(user.Id, rotated.RefreshToken);
        await auth.LoginAsync("analyst1", "TotallyWrong9!");
        await auth.ChangePasswordAsync(user.Id, CurrentPassword, ReplacementPassword);
        await users.SetStatusAsync(user.Id, isActive: false, reason: "Done", actingUserId: 1);

        var secrets = new[]
        {
            CurrentPassword, ReplacementPassword, "TotallyWrong9!",
            login.RefreshToken!, rotated.RefreshToken!, login.Token!,
            (await db.Users.FirstAsync(u => u.Id == user.Id)).PasswordHash
        };

        var events = await db.SecurityAuditEvents.ToListAsync();
        Assert.NotEmpty(events);

        foreach (var e in events)
        {
            var serialised = string.Join("|", e.EventCode, e.TargetUsername, e.CorrelationId,
                e.IpAddress, e.UserAgent, e.RequestPath, e.Source, e.Reason, e.Metadata);

            foreach (var secret in secrets)
                Assert.DoesNotContain(secret, serialised);
        }
    }

