    // ---------- Refresh rejections are security events too ----------

    // A locked account whose token was never revoked is the case that
    // reaches the account-state check: the token row is still active, so
    // only the re-read of the user stops the refresh.
    [Fact]
    public async Task RefreshRejectedForLockedAccount_RecordsAccountBlocked()
    {
        using var db = CreateDbContext();
        var user = SeedUser(db);
        var (_, auth) = CreateServices(db);
        var login = await auth.LoginAsync("analyst1", CurrentPassword);

        var stored = await db.Users.FirstAsync(u => u.Id == user.Id);
        stored.LockedUntil = DateTime.UtcNow.AddMinutes(15);
        await db.SaveChangesAsync();

        await auth.RefreshAsync(login.RefreshToken!);

        var rejected = Assert.Single(await EventsAsync(db, SecurityEventCodes.RefreshRejectedAccountBlocked));
        Assert.Equal(SecurityEventOutcome.Failure, rejected.Outcome);
        Assert.Equal(user.Id, rejected.TargetUserId);
        Assert.Equal("Account is locked.", rejected.Reason);
    }

    // Disabling revokes the token first, so a later refresh is rejected as
    // an invalid token rather than a blocked account - the earlier and
    // more precise reason. Either way the rejection is recorded.
    [Fact]
    public async Task RefreshAfterDisable_RecordsInvalidTokenRejection()
    {
        using var db = CreateDbContext();
        var user = SeedUser(db);
        var (users, auth) = CreateServices(db);
        var login = await auth.LoginAsync("analyst1", CurrentPassword);

        await users.SetStatusAsync(user.Id, isActive: false, reason: "Suspended", actingUserId: 1);
        await auth.RefreshAsync(login.RefreshToken!);

        var rejected = Assert.Single(await EventsAsync(db, SecurityEventCodes.RefreshRejectedInvalidToken));
        Assert.Equal(SecurityEventOutcome.Failure, rejected.Outcome);
        Assert.Equal(user.Id, rejected.TargetUserId);
    }

    [Fact]
    public async Task RefreshWithUnrecognisedToken_RecordsTheRejection_WithoutTheTokenValue()
